/// Progress phases reported by [`migrate`], in order (then the writer's own
/// phases for each commit, `publish`, and `directory`).
pub mod phase {
    pub const VERIFY_SOURCE: &str = "migrate-verify-source";
    pub const COPY: &str = "migrate-copy";
    pub const VERIFY: &str = "migrate-verify";
}

/// What a migration is told. `read` carries the limits and, for an Encrypted
/// source, the passphrases; they open the source and wrap the new archive.
/// [`ReadOptions::drafts`] is overridden: migration is the one reader of the
/// last draft.
#[derive(Debug, Clone, Default)]
pub struct MigrateOptions {
    pub read: ReadOptions,
    /// Argon2id parameters of the new archive's envelopes; `None`: the
    /// defaults. Encrypted archives only.
    pub kdf: Option<mochi_format::kdf::KdfParams>,
    /// The new archive's checkpoint trigger (B.2.3); `None`: the default.
    pub checkpoint_trigger: Option<CheckpointTrigger>,
    /// Test control: place the new archive's checkpoints exactly.
    #[cfg(any(test, feature = "test-controls"))]
    pub checkpoint_policy: Option<crate::publish::CheckpointPolicy>,
    /// Test control: make the copy disagree with its source, to show that the
    /// comparison (§26 step 6) catches it and nothing is published.
    #[cfg(any(test, feature = "test-controls"))]
    pub tamper: Option<Tamper>,
}

/// How a test makes the written archive differ from its source.
#[cfg(any(test, feature = "test-controls"))]
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Tamper {
    /// Write the last snapshot without its first path.
    DropLastPath,
    /// Write one version's POSIX mode changed.
    ChangeAttributes,
    /// Write no retention operations.
    DropRetention,
}

/// The source's own verification before anything is written (§26 step 2).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct SourceVerification {
    pub level: String,
    pub overall_status: Status,
    pub exit_code: u8,
    pub findings: u64,
}

/// The new archive's verification (§22.2 form), before publication.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct NewVerification {
    pub level: String,
    pub overall_status: Status,
    pub policy_result: Status,
    pub exit_code: u8,
    pub findings: u64,
}

/// What was compared with the source (§26 step 6). Every count is of items
/// that compared equal; a difference fails the migration instead.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct Comparison {
    /// Snapshots whose namespace (path to file-version ID) is identical.
    pub snapshots_compared: u64,
    /// File versions whose record (kind, length, content hash) and extents
    /// are identical.
    pub file_versions_compared: u64,
    /// Versions whose promised attributes are identical.
    pub attributes_compared: u64,
    /// Whether the retention state (holds and expiries) is identical.
    pub retention_equal: bool,
    /// File versions read back from the new archive, each hash-verified
    /// against the content hash the source recorded.
    pub versions_read_back: u64,
}

/// The profile both archives have.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct ProfileSummary {
    pub tar_compatible: bool,
    pub encrypted: bool,
    /// Parity percentage, when the Redundancy profile is on.
    pub redundancy_percent: Option<u16>,
}

impl From<Profile> for ProfileSummary {
    fn from(p: Profile) -> Self {
        ProfileSummary {
            tar_compatible: p.tar_compatible,
            encrypted: p.encrypted,
            redundancy_percent: p.redundancy,
        }
    }
}

/// What [`migrate`] did. The source is always kept (`source_kept`).
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
pub struct MigrateReport {
    pub source_archive_id: String,
    /// The draft the source was written under (always [`DRAFT_ID`]).
    pub source_draft: u64,
    pub source_head: PlanHead,
    pub source_len: u64,
    pub source_verification: SourceVerification,
    pub new_archive_id: String,
    pub new_len: u64,
    /// The new archive is a ratified archive (descriptor key 3 = null).
    pub new_ratified: bool,
    pub profile: ProfileSummary,
    /// The mapping: each source commit and the new commit reproducing it.
    pub commits: Vec<CommitMapping>,
    pub chunks_copied: u64,
    pub stored_bytes_copied: u64,
    pub file_versions: u64,
    pub comparison: Comparison,
    pub new_verification: NewVerification,
    /// The chunks were opened and sealed again under the new archive's own
    /// key (Encrypted profile, D20 item 10) instead of copied as they were.
    pub resealed: bool,
    /// `None`: the directory flush was confirmed.
    pub durability_unconfirmed: Option<String>,
    /// Always true: the source is never written or removed (§26 steps 1, 9).
    pub source_kept: bool,
    /// §26 steps 7 and 9, which are not this command's.
    pub not_done: &'static str,
}

/// The `not_done` text of every report.
pub const NOT_DONE: &str = "independent recovery copies (spec §26 step 7) are not made, and the \
     source is kept until you accept the migration and your retention policy allows removing \
     it (step 9)";

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// Verify the source at the restoration level (deep) and refuse anything that
/// does not exit 0 (a failed, unsupported, degraded, or overdue check): a source that does not verify is not converted, so no
/// damage is silently dropped or carried.
fn verify_source(
    src: &dyn ReadStorage,
    read: &ReadOptions,
    ctx: &JobContext<'_>,
) -> Result<SourceVerification> {
    ctx.report(phase::VERIFY_SOURCE, 0, None);
    let v = verify(
        src,
        &VerifyOptions {
            read: read.clone(),
            deep: true,
            ..VerifyOptions::default()
        },
        ctx,
    );
    ctx.check_cancelled()?;
    let r = &v.report;
    if r.exit_code == exit::OK && !r.operational_error {
        return Ok(SourceVerification {
            level: format!("{:?}", r.level).to_lowercase(),
            overall_status: r.overall_status,
            exit_code: r.exit_code,
            findings: r.findings.len() as u64,
        });
    }
    // The first finding that is an error names the code; an archive that is
    // not PASS for another reason (degraded protection, an unsupported
    // check) is refused as a record problem with the status in the message.
    let first = r
        .findings
        .iter()
        .find(|f| f.severity == Severity::Error)
        .or_else(|| r.findings.first());
    let code = first.map_or(ErrorCode::RecordInvalid, |f| f.code);
    let detail = first
        .map(|f| {
            format!(
                "; first finding {}{}",
                f.code,
                f.message
                    .as_deref()
                    .map(|m| format!(": {m}"))
                    .unwrap_or_default()
            )
        })
        .unwrap_or_default();
    Err(MochiError::new(
        code,
        format!(
            "the source does not verify at the restoration level (overall {:?}, exit {}){detail}. \
             Migration converts only an archive that verifies; it never converts a damaged one \
             partially. Nothing was written. Look at it with `mochi verify`, and repair it with \
             `mochi repair plan` first",
            r.overall_status, r.exit_code
        ),
    ))
}

/// Migrate the draft archive `src` into a new 1.0 archive `name` in `dir`.
/// See the module documentation.
pub fn migrate<D>(
    src: &dyn ReadStorage,
    dir: &mut D,
    name: &str,
    ids: Box<dyn IdSource>,
    options: &MigrateOptions,
    ctx: &JobContext<'_>,
) -> Result<MigrateReport>
where
    D: StorageDir,
    D::File: Storage,
{
    // The one reader of the last draft. The new archive is read back with
    // the same options: it is ratified, which they accept as well.
    let opts = ReadOptions {
        drafts: DraftPolicy::AllowLastDraft,
        ..options.read.clone()
    };
    let head = open_head(src, &opts)?;
    match head.descriptor.draft {
        Some(DRAFT_ID) => {}
        Some(other) => {
            // Unreachable while `AllowLastDraft` admits only DRAFT_ID.
            return Err(MochiError::new(
                ErrorCode::UnsupportedFeature,
                format!(
                    "archive was written under draft {other}; migration reads only draft \
                     {DRAFT_ID}"
                ),
            ));
        }
        None => {
            return Err(MochiError::new(
                ErrorCode::InvalidArgument,
                "this archive is already a ratified (1.0) archive; there is nothing to migrate. \
                 Nothing was written",
            ));
        }
    }
    let source_verification = verify_source(src, &opts, ctx)?;

    let head_seq = head.commit.seq;
    let source_head = PlanHead {
        seq: head_seq,
        commit_id: hex(head.commit_id.as_bytes()),
        footer_offset: head.location.footer.footer_offset,
        committed_len: head.location.committed_len,
    };
    let profile = head.descriptor.profile();
    let retention = resolve_retention(src, &head, &opts)?;
    let attributes = all_attributes(src, &opts)?;
    let history = commit_history(src, &opts)?;
    let by_seq: BTreeMap<u64, _> = history.iter().map(|h| (h.commit.seq, h)).collect();
    let source_commit = |s: u64| {
        by_seq.get(&s).copied().ok_or_else(|| {
            MochiError::new(
                ErrorCode::RecordInvalid,
                format!("commit {s} is missing from the history"),
            )
        })
    };
    let (chunk_size, zstd_level) = recorded_writer_parameters(&head.catalog)?.ok_or_else(|| {
        MochiError::new(
            ErrorCode::RecordInvalid,
            "the source records no writer parameters",
        )
    })?;

    // The source's snapshots, in order.
    let mut source_namespaces = Vec::new();
    head.catalog.replay_each(|seq, s| {
        source_namespaces.push((seq, namespace(s)));
        Ok(())
    })?;
    if source_namespaces.len() as u64 != head_seq + 1 {
        return Err(MochiError::new(
            ErrorCode::RecordInvalid,
            "the source's history does not replay to one snapshot per commit",
        ));
    }
    let version_ids: BTreeSet<FileVersionId> = source_namespaces
        .iter()
        .flat_map(|(_, n)| n.values().copied())
        .collect();

    // Retention carries over on the same sequence numbers (every snapshot is
    // kept, so the numbering is unchanged).
    let mut retention_ops: Vec<RetentionOp> = retention
        .expired
        .iter()
        .map(|s| RetentionOp::Expire { seq: *s })
        .collect();
    retention_ops.extend(retention.holds.iter().map(|(l, s)| RetentionOp::Hold {
        label: l.clone(),
        seq: *s,
    }));

    let wopts = WriterOptions {
        threads: None,
        chunk_size: Some(chunk_size),
        zstd_level: Some(zstd_level),
        record_time: false,
        dedup: Dedup::Off,
        // The profile is kept; a TAR-compatible source gets its stream
        // framing regenerated and a Redundancy source its parity, by the
        // writer (Annex B.2.9 D19 rule 9; B.2.11 D21).
        profile: Some(profile),
        // The passphrases are the new archive's, and its key is new (D20
        // item 10): nothing sealed in the source is carried over.
        read: opts.clone(),
        kdf: options.kdf,
        checkpoint_trigger: options.checkpoint_trigger,
    };

    #[cfg(any(test, feature = "test-controls"))]
    let tamper = options.tamper;
    #[cfg(not(any(test, feature = "test-controls")))]
    let tamper: Option<()> = None;
    #[cfg(any(test, feature = "test-controls"))]
    let attributes_written = {
        let mut a = attributes.clone();
        if tamper == Some(Tamper::ChangeAttributes) {
            if let Some(p) = a.values_mut().find_map(|x| x.posix.as_mut()) {
                p.mode ^= 0o1;
            }
        }
        a
    };
    #[cfg(not(any(test, feature = "test-controls")))]
    let attributes_written = &attributes;
    let mut copier = Copier::default();
    let mut new_ids: Vec<String> = Vec::new();
    let mut comparison = None;
    let mut new_verification = None;
    let mut new_archive_id = None;
    let total = Some(head_seq + 1);

    let (writer, (), durability) = ArchiveWriter::build_in(dir, name, ids, wopts, ctx, |w| {
        #[cfg(any(test, feature = "test-controls"))]
        if let Some(p) = options.checkpoint_policy {
            w.set_checkpoint_policy(p)?;
        }
        let last = head_seq;
        head.catalog.replay_each(|seq, snapshot| {
            ctx.check_cancelled()?;
            let time = source_commit(seq)?.commit.time;
            #[cfg_attr(not(any(test, feature = "test-controls")), allow(unused_mut))]
            let mut written_ns = namespace(snapshot);
            #[cfg(any(test, feature = "test-controls"))]
            if tamper == Some(Tamper::DropLastPath) && seq == last {
                if let Some(k) = written_ns.keys().next().cloned() {
                    written_ns.remove(&k);
                }
            }
            let outcome = copier.commit(
                w,
                src,
                &head.catalog,
                written_ns,
                &attributes_written,
                &opts,
                ctx,
                |tx| {
                    #[cfg(any(test, feature = "test-controls"))]
                    let keep_retention = tamper != Some(Tamper::DropRetention);
                    #[cfg(not(any(test, feature = "test-controls")))]
                    let keep_retention = tamper.is_none();
                    if seq == last && keep_retention {
                        for op in &retention_ops {
                            tx.push_retention(op.clone());
                        }
                    }
                    if let Some(t) = time {
                        tx.at(t);
                    }
                },
            )?;
            if outcome.seq != seq {
                return Err(MochiError::new(
                    ErrorCode::InvalidArgument,
                    "internal: the new archive's sequence ran ahead of the mapping",
                ));
            }
            new_ids.push(hex(outcome.commit_id.as_bytes()));
            ctx.report(phase::COPY, copier.commits(), total);
            Ok(())
        })?;

        // §26 step 6 against what was written, before publication.
        ctx.report(phase::VERIFY, 0, None);
        let out: &dyn ReadStorage = w.storage();
        let new_head = open_head(out, &opts)?;
        let fail = |what: String| {
            MochiError::new(
                ErrorCode::CheckpointMismatch,
                format!("the migrated archive does not reproduce its source: {what}"),
            )
        };
        if new_head.descriptor.draft.is_some() {
            return Err(fail("the new descriptor is not ratified".into()));
        }
        copier.check_namespaces(&new_head, &fail)?;
        let mut new_namespaces = Vec::new();
        new_head.catalog.replay_each(|seq, s| {
            new_namespaces.push((seq, namespace(s)));
            Ok(())
        })?;
        if new_namespaces != source_namespaces {
            return Err(fail("a snapshot's namespace differs".into()));
        }
        let mut compared = 0u64;
        for id in &version_ids {
            ctx.check_cancelled()?;
            let old = head.catalog.file_version(id)?;
            let new = new_head.catalog.file_version(id)?;
            if old.is_none() || old != new {
                return Err(fail(format!(
                    "file version {id:?} differs (record, content hash, or extents)"
                )));
            }
            compared += 1;
        }
        let written = all_attributes(out, &opts)?;
        let want: BTreeMap<_, _> = version_ids
            .iter()
            .map(|id| {
                attributes
                    .get(id)
                    .map(|a| (*id, *a))
                    .ok_or_else(|| fail("attributes".into()))
            })
            .collect::<Result<_>>()?;
        if written != want {
            return Err(fail("promised attributes differ".into()));
        }
        if segment_state(out, &new_head, &opts)?.retention != retention {
            return Err(fail("the retention state differs".into()));
        }
        let mut read_back = 0u64;
        for id in &version_ids {
            let (v, _) = new_head
                .catalog
                .file_version(id)?
                .ok_or_else(|| fail("a listed version is missing".into()))?;
            if v.kind == EntryKind::Directory {
                continue;
            }
            ctx.check_cancelled()?;
            // `read_version` hash-verifies the stored bytes and the file
            // hash; the hash it checks is the catalog's, which was just
            // compared equal to the source's.
            read_version(out, &new_head.catalog, id, &mut std::io::sink(), &opts, ctx)?;
            read_back += 1;
        }
        comparison = Some(Comparison {
            snapshots_compared: new_namespaces.len() as u64,
            file_versions_compared: compared,
            attributes_compared: written.len() as u64,
            retention_equal: true,
            versions_read_back: read_back,
        });

        // §22.2 form: the new archive verifies at the restoration level.
        let v = verify(
            out,
            &VerifyOptions {
                read: opts.clone(),
                deep: true,
                ..VerifyOptions::default()
            },
            ctx,
        );
        if v.report.operational_error {
            let what = v
                .report
                .findings
                .first()
                .and_then(|f| f.message.clone())
                .unwrap_or_default();
            return Err(MochiError::new(
                ErrorCode::IoError,
                format!("verifying the migrated archive did not complete: {what}"),
            ));
        }
        if v.report.exit_code != exit::OK {
            return Err(fail(format!(
                "verification reports {:?} (exit {})",
                v.report.overall_status, v.report.exit_code
            )));
        }
        new_verification = Some(NewVerification {
            level: format!("{:?}", v.report.level).to_lowercase(),
            overall_status: v.report.overall_status,
            policy_result: v.report.policy_result,
            exit_code: v.report.exit_code,
            findings: v.report.findings.len() as u64,
        });
        new_archive_id = Some(hex(new_head.commit.archive_id.as_bytes()));
        Ok(())
    })?;

    let new_len = writer.storage().size()?;
    drop(writer);
    let missing = |what: &str| {
        MochiError::new(
            ErrorCode::InvalidArgument,
            format!("internal: no {what} after the build"),
        )
    };
    Ok(MigrateReport {
        source_archive_id: hex(head.commit.archive_id.as_bytes()),
        source_draft: DRAFT_ID,
        source_head,
        source_len: src.size()?,
        source_verification,
        new_archive_id: new_archive_id.ok_or_else(|| missing("archive id"))?,
        new_len,
        new_ratified: true,
        profile: profile.into(),
        commits: new_ids
            .into_iter()
            .enumerate()
            .map(|(i, id)| {
                let seq = i as u64;
                Ok(CommitMapping {
                    source_seq: seq,
                    source_commit_id: hex(source_commit(seq)?.commit_id.as_bytes()),
                    new_seq: seq,
                    new_commit_id: id,
                })
            })
            .collect::<Result<_>>()?,
        chunks_copied: copier.chunks_copied,
        stored_bytes_copied: copier.bytes_copied,
        file_versions: version_ids.len() as u64,
        comparison: comparison.ok_or_else(|| missing("comparison"))?,
        new_verification: new_verification.ok_or_else(|| missing("verification"))?,
        resealed: head.commit.encrypted(),
        durability_unconfirmed: match durability {
            Some(PublishDurability::DirectoryUnconfirmed(why)) => Some(why),
            _ => None,
        },
        source_kept: true,
        not_done: NOT_DONE,
    })
}
