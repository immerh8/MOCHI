//! Migration of the last draft to a ratified archive (spec §26, Annex B.2.14
//! D24; plan K25, W20).
//!
//! [`migrate`] reads **only the last draft** (draft 2: descriptor key 3 = 2)
//! and writes a **new 1.0 archive** (key 3 = null) through the rewrite path
//! ([`Copier`], as `compact` and `repair` do). Every other command refuses a
//! draft archive; older drafts are refused here too.
//!
//! The §26 steps it performs, in order, all before publication (the new
//! archive is built in a temporary file by [`ArchiveWriter::build_in`]; any
//! failure, refusal, or cancellation leaves nothing at the destination name):
//!
//! 1. the source is **preserved**: it is read through [`ReadStorage`] and never
//!    opened for writing, locked, or truncated;
//! 2. the source's readable content is **verified** at the restoration level
//!    (deep). A source that does not verify is refused, never converted
//!    partially: repair it first;
//! 3. the deterministic snapshot semantics are **reconstructed**: one commit
//!    per source snapshot, in order, the same namespace, the same file-version
//!    IDs and attributes, the same stored chunks byte for byte (an Encrypted
//!    source is opened and sealed again under the new archive's own key, D20
//!    item 10, so it needs the passphrase);
//! 4. recovery manifests are created by the ordinary writer (the current
//!    manifest schemas are this build's only kind);
//! 5. the new representation is written (profile kept; parity and TAR framing
//!    regenerated by the writer);
//! 6. the restored file hashes and the retained namespaces are **compared**
//!    with the source's: every snapshot's namespace, every file version's
//!    record and extents, the promised attributes, the retention state, and a
//!    read-back of every file version;
//! 8. the **mapping and evidence** are the returned [`MigrateReport`].
//!
//! Not done, and said so in the report: step 7 (independent recovery copies)
//! and step 9 (retaining the source until the user accepts the migration):
//! the source is kept and removing it is the user's explicit action.
//!
//! Nothing is invented: no provenance record is written (the manifest's
//! rewrite reasons are `collection` and `reencryption`, and a third value
//! would be a wire change), and the report's mapping is the only record of
//! which source commit each new commit reproduces. Commit IDs bind footer
//! offsets, so freshness anchors start over; first sight of the new archive
//! is `UNKNOWN`.

